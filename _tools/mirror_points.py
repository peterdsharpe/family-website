"""Make assets/mirror-points.js, the data behind the mirror on the home page.

The real mirror (github.com/peterdsharpe/mirror-array) is a hexagon of 294
triangular mirrors. Each one is tilted so that its patch of sunlight lands on
one point of a message. Here the message is "hello", written in Hershey's
single-stroke script, and each mirror is matched to a point by solving the
assignment problem on squared distance. Matching near mirrors to near points is
what keeps the writing legible when the wall is nearer or farther than the
design distance, which is the hard part of the real project too.

    uv run --with Hershey-Fonts --with numpy --with scipy python _tools/mirror_points.py
"""

from pathlib import Path

import numpy as np
from HersheyFonts import HersheyFonts
from scipy.optimize import linear_sum_assignment

N_SIDE = 7  # a hexagon of side 7 holds 6 * 7**2 = 294 unit triangles
WORD = "hello"
OUT = Path(__file__).resolve().parent.parent / "assets" / "mirror-points.js"


def hexagon_triangles(n):
    """Centroids and orientations (+1 up, -1 down) of the unit triangles that
    tile a regular hexagon of side n, centred on the origin, flat top and
    bottom. Unit triangles have side 1."""
    h = np.sqrt(3) / 2
    out = []
    for j in range(-n, n):  # rows of triangles, bottom to top
        y0 = j * h
        bottom = 0.5 * (j % 2)  # x offset of lattice points on the row's lower edge
        top = 0.5 * ((j + 1) % 2)
        for k in range(-2 * n, 2 * n + 1):
            out.append((k + bottom + 0.5, y0 + h / 3, 1))  # pointing up
            out.append((k + top + 0.5, y0 + 2 * h / 3, -1))  # pointing down
    pts = np.array(out)
    x, y = pts[:, 0], pts[:, 1]
    inside = (np.abs(y) < n * h) & (np.abs(x) < n - np.abs(y) / np.sqrt(3))
    return pts[inside]


def chaikin(poly, iterations=3):
    p = np.asarray(poly, float)
    for _ in range(iterations):
        q = 0.75 * p[:-1] + 0.25 * p[1:]
        r = 0.25 * p[:-1] + 0.75 * p[1:]
        p = np.vstack([p[:1], np.column_stack([q, r]).reshape(-1, 2), p[-1:]])
    return p


def strokes_for(word):
    font = HersheyFonts()
    font.load_default_font("scripts")
    font.normalize_rendering(100)
    strokes, current = [], []
    for a, b in font.lines_for_text(word):
        if current and np.allclose(current[-1], a):
            current.append(b)
        else:
            if current:
                strokes.append(current)
            current = [a, b]
    strokes.append(current)
    return [chaikin(s) for s in strokes]


def resample(strokes, count):
    """Spread `count` points evenly by arc length over all strokes."""
    lengths = [np.linalg.norm(np.diff(s, axis=0), axis=1) for s in strokes]
    total = sum(l.sum() for l in lengths)
    step = total / count
    points, carry = [], 0.0
    for s, seg in zip(strokes, lengths):
        cum = np.concatenate([[0], np.cumsum(seg)])
        d = carry
        while d <= cum[-1] + 1e-9 and len(points) < count:
            k = min(np.searchsorted(cum, d, side="right") - 1, len(seg) - 1)
            f = (d - cum[k]) / seg[k] if seg[k] else 0
            points.append(s[k] + f * (s[k + 1] - s[k]))
            d += step
        carry = d - cum[-1]
    while len(points) < count:
        points.append(strokes[-1][-1])
    return np.array(points[:count])


def main():
    tri = hexagon_triangles(N_SIDE)
    assert len(tri) == 6 * N_SIDE**2, len(tri)

    # Design space: a 1600 x 1000 wall with the mirror's light centred on it.
    target = resample(strokes_for(WORD), len(tri))
    target[:, 1] *= -1  # font y points up; canvas y points down
    lo, hi = target.min(0), target.max(0)
    scale = 1180 / (hi[0] - lo[0])
    target = (target - (lo + hi) / 2) * scale + [800, 500]

    # Tile side chosen so that neighbouring spots of writing just touch.
    stroke_len = sum(np.linalg.norm(np.diff(s, axis=0), axis=1).sum() for s in strokes_for(WORD))
    side = stroke_len * scale / len(tri) * 1.05
    mirror = tri[:, :2] * side + [800, 500]
    mirror[:, 1] = 1000 - mirror[:, 1]  # flip to canvas y

    cost = ((mirror[:, None, :] - target[None, :, :]) ** 2).sum(-1)
    rows, cols = linear_sum_assignment(cost)
    target = target[cols[np.argsort(rows)]]

    fmt = lambda a: ",".join(f"{v:.1f}".rstrip("0").rstrip(".") for v in a)
    OUT.write_text(
        "// Generated by _tools/mirror_points.py; do not edit by hand.\n"
        f"export const side = {side:.2f};\n"
        f"export const mirrorX = [{fmt(mirror[:, 0])}];\n"
        f"export const mirrorY = [{fmt(mirror[:, 1])}];\n"
        f"export const up = [{','.join('1' if u > 0 else '0' for u in tri[:, 2])}];\n"
        f"export const targetX = [{fmt(target[:, 0])}];\n"
        f"export const targetY = [{fmt(target[:, 1])}];\n"
    )
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes), side {side:.1f}")


if __name__ == "__main__":
    main()
